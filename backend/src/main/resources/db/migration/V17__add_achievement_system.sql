CREATE TABLE achievements (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              code VARCHAR(50) NOT NULL,

                              title VARCHAR(100) NOT NULL,

                              description VARCHAR(500) NOT NULL,

                              condition_type VARCHAR(40) NOT NULL,

                              threshold INTEGER NOT NULL,

                              display_order INTEGER NOT NULL,

                              active BOOLEAN NOT NULL DEFAULT TRUE,

                              created_at TIMESTAMPTZ NOT NULL
                                                      DEFAULT CURRENT_TIMESTAMP,

                              updated_at TIMESTAMPTZ NOT NULL
                                                      DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT uk_achievements_code
                                  UNIQUE (code),

                              CONSTRAINT chk_achievements_condition
                                  CHECK (
                                      condition_type IN (
                                                         'FIRST_CORRECT_CHALLENGE',
                                                         'FIRST_SIMULATION',
                                                         'XP_AT_LEAST',
                                                         'ALL_SKILLS_AT_LEAST'
                                          )
                                      ),

                              CONSTRAINT chk_achievements_threshold
                                  CHECK (threshold >= 0),

                              CONSTRAINT chk_achievements_display_order
                                  CHECK (display_order >= 0)
);


CREATE TABLE child_achievements (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    child_profile_id BIGINT NOT NULL,

                                    achievement_id BIGINT NOT NULL,

                                    earned_at TIMESTAMPTZ NOT NULL
                                        DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_child_achievements_child
                                        FOREIGN KEY (child_profile_id)
                                            REFERENCES child_profiles(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT fk_child_achievements_achievement
                                        FOREIGN KEY (achievement_id)
                                            REFERENCES achievements(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT uk_child_achievements_child_achievement
                                        UNIQUE (
                                                child_profile_id,
                                                achievement_id
                                            )
);


CREATE INDEX idx_child_achievements_child
    ON child_achievements(child_profile_id);


