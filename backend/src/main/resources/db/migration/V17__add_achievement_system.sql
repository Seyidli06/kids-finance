-- Existing XP
INSERT INTO child_achievements (
    child_profile_id,
    achievement_id
)
SELECT
    cp.id,
    a.id
FROM child_profiles cp
         JOIN achievements a
              ON a.code = 'XP_50'
WHERE cp.xp >= a.threshold
    ON CONFLICT DO NOTHING;


-- Existing balanced skill scores
INSERT INTO child_achievements (
    child_profile_id,
    achievement_id
)
SELECT
    css.child_profile_id,
    a.id
FROM child_skill_scores css
         JOIN achievements a
              ON a.code = 'BALANCED_50'
GROUP BY
    css.child_profile_id,
    a.id,
    a.threshold
HAVING
    COUNT(*) = 5
   AND MIN(css.score) >= a.threshold
    ON CONFLICT DO NOTHING;