-- Existing correct challenge history
INSERT INTO child_achievements (
    child_profile_id,
    achievement_id
)
SELECT DISTINCT
    ca.child_profile_id,
    a.id
FROM challenge_attempts ca
         JOIN achievements a
              ON a.code = 'FIRST_CHALLENGE'
WHERE ca.correct = TRUE
    ON CONFLICT DO NOTHING;


-- Existing simulation history
