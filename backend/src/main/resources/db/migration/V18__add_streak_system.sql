CREATE TABLE child_streaks (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               child_profile_id BIGINT NOT NULL,

                               current_streak INTEGER NOT NULL DEFAULT 0,

                               longest_streak INTEGER NOT NULL DEFAULT 0,

                               last_activity_date DATE,

                               created_at TIMESTAMPTZ NOT NULL
                                                               DEFAULT CURRENT_TIMESTAMP,

                               updated_at TIMESTAMPTZ NOT NULL
                                                               DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_child_streaks_child
                                   FOREIGN KEY (child_profile_id)
                                       REFERENCES child_profiles(id)
                                       ON DELETE CASCADE,

                               CONSTRAINT uk_child_streaks_child
                                   UNIQUE (child_profile_id),

                               CONSTRAINT chk_child_streaks_current
                                   CHECK (current_streak >= 0),

                               CONSTRAINT chk_child_streaks_longest
                                   CHECK (longest_streak >= 0),

                               CONSTRAINT chk_child_streaks_longest_current
                                   CHECK (longest_streak >= current_streak)
);


