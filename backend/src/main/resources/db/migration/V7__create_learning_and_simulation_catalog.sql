CREATE TABLE learning_topics (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 code VARCHAR(50) NOT NULL,

                                 title VARCHAR(100) NOT NULL,

                                 description VARCHAR(500),

                                 display_order INTEGER NOT NULL,

                                 active BOOLEAN NOT NULL DEFAULT TRUE,

                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT uk_learning_topics_code
                                     UNIQUE (code),

                                 CONSTRAINT chk_learning_topics_display_order
                                     CHECK (display_order >= 0)
);


CREATE TABLE simulation_scenarios (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                      code VARCHAR(50) NOT NULL,

                                      learning_topic_id BIGINT NOT NULL,

                                      title VARCHAR(150) NOT NULL,

                                      description VARCHAR(1000) NOT NULL,

                                      display_order INTEGER NOT NULL,

                                      active BOOLEAN NOT NULL DEFAULT TRUE,

                                      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT uk_simulation_scenarios_code
                                          UNIQUE (code),

                                      CONSTRAINT fk_simulation_scenarios_learning_topic
                                          FOREIGN KEY (learning_topic_id)
                                              REFERENCES learning_topics(id),

                                      CONSTRAINT chk_simulation_scenarios_display_order
                                          CHECK (display_order >= 0)
);


CREATE TABLE simulation_options (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    scenario_id BIGINT NOT NULL,

                                    code VARCHAR(50) NOT NULL,

                                    title VARCHAR(150) NOT NULL,

                                    description VARCHAR(1000),

                                    cost NUMERIC(19, 2) NOT NULL DEFAULT 0.00,

                                    display_order INTEGER NOT NULL,

                                    active BOOLEAN NOT NULL DEFAULT TRUE,

                                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_simulation_options_scenario
                                        FOREIGN KEY (scenario_id)
                                            REFERENCES simulation_scenarios(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT uk_simulation_options_scenario_code
                                        UNIQUE (scenario_id, code),

                                    CONSTRAINT chk_simulation_options_cost
                                        CHECK (cost >= 0),

                                    CONSTRAINT chk_simulation_options_display_order
                                        CHECK (display_order >= 0)
);


CREATE INDEX idx_simulation_scenarios_learning_topic
    ON simulation_scenarios (learning_topic_id);


CREATE INDEX idx_simulation_options_scenario
    ON simulation_options (scenario_id);