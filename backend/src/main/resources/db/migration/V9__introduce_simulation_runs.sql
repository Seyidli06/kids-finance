CREATE TABLE simulation_runs (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 child_profile_id BIGINT NOT NULL,

                                 scenario_id BIGINT NOT NULL,

                                 status VARCHAR(20) NOT NULL,

                                 started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 completed_at TIMESTAMPTZ,

                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT fk_simulation_runs_child
                                     FOREIGN KEY (child_profile_id)
                                         REFERENCES child_profiles(id)
                                         ON DELETE CASCADE,

                                 CONSTRAINT fk_simulation_runs_scenario
                                     FOREIGN KEY (scenario_id)
                                         REFERENCES simulation_scenarios(id),

                                 CONSTRAINT chk_simulation_runs_status
                                     CHECK (
                                         status IN (
                                                    'IN_PROGRESS',
                                                    'COMPLETED',
                                                    'ABANDONED'
                                             )
                                         ),

                                 CONSTRAINT chk_simulation_runs_completed_at
                                     CHECK (
                                         completed_at IS NULL
                                             OR completed_at >= started_at
                                         )
);


CREATE INDEX idx_simulation_runs_child
    ON simulation_runs(child_profile_id);

CREATE INDEX idx_simulation_runs_scenario
    ON simulation_runs(scenario_id);

CREATE INDEX idx_simulation_runs_child_scenario
    ON simulation_runs(child_profile_id, scenario_id);


-- Existing decisions will be connected to runs.
ALTER TABLE simulation_decisions
    ADD COLUMN run_id BIGINT;

ALTER TABLE simulation_decisions
    ADD COLUMN option_id BIGINT;


-- Create one completed run for every historical decision.
-- We reuse the old decision id as the run id so that
-- backfilling remains deterministic.
INSERT INTO simulation_runs (
    id,
    child_profile_id,
    scenario_id,
    status,
    started_at,
    completed_at,
    created_at,
    updated_at
)
SELECT
    sd.id,
    sd.child_profile_id,
    ss.id,
    'COMPLETED',
    sd.created_at,
    sd.created_at,
    sd.created_at,
    sd.created_at
FROM simulation_decisions sd
         JOIN simulation_scenarios ss
              ON ss.code = sd.scenario_code;


-- Link historical decisions to their new runs.
UPDATE simulation_decisions
SET run_id = id;


-- Link historical decisions to the canonical simulation option.
UPDATE simulation_decisions sd
SET option_id = so.id
    FROM simulation_runs sr
JOIN simulation_options so
ON so.scenario_id = sr.scenario_id
WHERE sr.id = sd.run_id
  AND so.code = sd.option_code;


-- If any old decision cannot be mapped,
-- these NOT NULL operations intentionally fail the migration.
ALTER TABLE simulation_decisions
    ALTER COLUMN run_id SET NOT NULL;

ALTER TABLE simulation_decisions
    ALTER COLUMN option_id SET NOT NULL;


ALTER TABLE simulation_decisions
    ADD CONSTRAINT fk_simulation_decisions_run
        FOREIGN KEY (run_id)
            REFERENCES simulation_runs(id)
            ON DELETE CASCADE;

ALTER TABLE simulation_decisions
    ADD CONSTRAINT fk_simulation_decisions_option
        FOREIGN KEY (option_id)
            REFERENCES simulation_options(id);


-- This is the constraint that previously prevented replay.
ALTER TABLE simulation_decisions
DROP CONSTRAINT uk_simulation_decisions_child_scenario;


CREATE INDEX idx_simulation_decisions_run
    ON simulation_decisions(run_id);

CREATE INDEX idx_simulation_decisions_option
    ON simulation_decisions(option_id);

CREATE INDEX idx_simulation_decisions_child_scenario
    ON simulation_decisions(
                            child_profile_id,
                            scenario_code
        );


-- Existing explicit run IDs must not confuse the identity sequence.
SELECT setval(
               pg_get_serial_sequence(
                       'simulation_runs',
                       'id'
               ),
               COALESCE(
                       (
                           SELECT MAX(id)
                           FROM simulation_runs
                       ),
                       1
               ),
               EXISTS (
                   SELECT 1
                   FROM simulation_runs
               )
       );