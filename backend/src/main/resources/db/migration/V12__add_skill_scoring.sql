CREATE TABLE child_skill_scores (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    child_profile_id BIGINT NOT NULL,

                                    skill_type VARCHAR(30) NOT NULL,

                                    score INTEGER NOT NULL DEFAULT 0,

                                    activity_count INTEGER NOT NULL DEFAULT 0,

                                    created_at TIMESTAMPTZ NOT NULL
                                        DEFAULT CURRENT_TIMESTAMP,

                                    updated_at TIMESTAMPTZ NOT NULL
                                        DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_child_skill_scores_child
                                        FOREIGN KEY (child_profile_id)
                                            REFERENCES child_profiles(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT uk_child_skill_scores_child_skill
                                        UNIQUE (
                                                child_profile_id,
                                                skill_type
                                            ),

                                    CONSTRAINT chk_child_skill_scores_skill
                                        CHECK (
                                            skill_type IN (
                                                           'SAVING',
                                                           'BUDGETING',
                                                           'RISK_MANAGEMENT',
                                                           'INVESTMENT',
                                                           'DECISION_MAKING'
                                                )
                                            ),

                                    CONSTRAINT chk_child_skill_scores_score
                                        CHECK (
                                            score BETWEEN 0 AND 100
                                            ),

                                    CONSTRAINT chk_child_skill_scores_activity_count
                                        CHECK (
                                            activity_count >= 0
                                            )
);


INSERT INTO child_skill_scores (
    child_profile_id,
