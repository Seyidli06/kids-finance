CREATE TABLE challenges (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            code VARCHAR(50) NOT NULL,

                            learning_topic_id BIGINT NOT NULL,

                            title VARCHAR(150) NOT NULL,

                            prompt VARCHAR(1000) NOT NULL,

                            explanation VARCHAR(1000) NOT NULL,

                            xp_reward INTEGER NOT NULL DEFAULT 10,

                            display_order INTEGER NOT NULL,

                            active BOOLEAN NOT NULL DEFAULT TRUE,

                            created_at TIMESTAMPTZ NOT NULL
                                                       DEFAULT CURRENT_TIMESTAMP,

                            updated_at TIMESTAMPTZ NOT NULL
                                                       DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT uk_challenges_code
                                UNIQUE (code),

                            CONSTRAINT fk_challenges_learning_topic
                                FOREIGN KEY (learning_topic_id)
                                    REFERENCES learning_topics(id),

                            CONSTRAINT chk_challenges_xp_reward
                                CHECK (xp_reward >= 0),

                            CONSTRAINT chk_challenges_display_order
                                CHECK (display_order >= 0)
);


CREATE TABLE challenge_options (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   challenge_id BIGINT NOT NULL,

                                   code VARCHAR(50) NOT NULL,

                                   text VARCHAR(500) NOT NULL,

                                   correct BOOLEAN NOT NULL,

                                   display_order INTEGER NOT NULL,

                                   active BOOLEAN NOT NULL DEFAULT TRUE,

                                   created_at TIMESTAMPTZ NOT NULL
                                                           DEFAULT CURRENT_TIMESTAMP,

                                   updated_at TIMESTAMPTZ NOT NULL
                                                           DEFAULT CURRENT_TIMESTAMP,

                                   CONSTRAINT fk_challenge_options_challenge
                                       FOREIGN KEY (challenge_id)
                                           REFERENCES challenges(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT uk_challenge_options_challenge_code
                                       UNIQUE (challenge_id, code),

                                   CONSTRAINT chk_challenge_options_display_order
                                       CHECK (display_order >= 0)
);


CREATE TABLE challenge_attempts (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                    child_profile_id BIGINT NOT NULL,

                                    challenge_id BIGINT NOT NULL,

                                    selected_option_id BIGINT NOT NULL,

                                    correct BOOLEAN NOT NULL,

                                    xp_awarded INTEGER NOT NULL DEFAULT 0,

                                    created_at TIMESTAMPTZ NOT NULL
                                                                DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT fk_challenge_attempts_child
                                        FOREIGN KEY (child_profile_id)
                                            REFERENCES child_profiles(id)
                                            ON DELETE CASCADE,

                                    CONSTRAINT fk_challenge_attempts_challenge
                                        FOREIGN KEY (challenge_id)
                                            REFERENCES challenges(id),

                                    CONSTRAINT fk_challenge_attempts_option
                                        FOREIGN KEY (selected_option_id)
                                            REFERENCES challenge_options(id),

                                    CONSTRAINT chk_challenge_attempts_xp
                                        CHECK (xp_awarded >= 0)
);


CREATE INDEX idx_challenges_learning_topic
    ON challenges(learning_topic_id);

CREATE INDEX idx_challenge_options_challenge
    ON challenge_options(challenge_id);

CREATE INDEX idx_challenge_attempts_child
    ON challenge_attempts(child_profile_id);

CREATE INDEX idx_challenge_attempts_challenge
    ON challenge_attempts(challenge_id);