CREATE TABLE main_simulation_runs (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                      child_profile_id BIGINT NOT NULL,

                                      starting_amount NUMERIC(19, 2) NOT NULL,

                                      cash_amount NUMERIC(19, 2) NOT NULL,
                                      saving_amount NUMERIC(19, 2) NOT NULL,
                                      deposit_amount NUMERIC(19, 2) NOT NULL,
                                      bond_amount NUMERIC(19, 2) NOT NULL,
                                      investment_amount NUMERIC(19, 2) NOT NULL,
                                      spending_amount NUMERIC(19, 2) NOT NULL,
                                      business_amount NUMERIC(19, 2) NOT NULL,

                                      portfolio_value_before_event NUMERIC(19, 2)
                                          NOT NULL,

                                      event_type VARCHAR(40) NOT NULL,

                                      event_delta NUMERIC(19, 2) NOT NULL,

                                      ending_amount NUMERIC(19, 2) NOT NULL,

                                      net_change NUMERIC(19, 2) NOT NULL,

                                      xp_earned INTEGER NOT NULL DEFAULT 0,

                                      created_at TIMESTAMPTZ NOT NULL
                                                                 DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT fk_main_simulation_runs_child
                                          FOREIGN KEY (child_profile_id)
                                              REFERENCES child_profiles(id)
                                              ON DELETE CASCADE,

                                      CONSTRAINT chk_main_simulation_start
                                          CHECK (starting_amount = 1000.00),

                                      CONSTRAINT chk_main_simulation_allocations
                                          CHECK (
                                              cash_amount >= 0
                                                  AND saving_amount >= 0
                                                  AND deposit_amount >= 0
                                                  AND bond_amount >= 0
                                                  AND investment_amount >= 0
                                                  AND spending_amount >= 0
                                                  AND business_amount >= 0
                                              ),

                                      CONSTRAINT chk_main_simulation_allocation_total
                                          CHECK (
                                              cash_amount
                                                  + saving_amount
                                                  + deposit_amount
                                                  + bond_amount
                                                  + investment_amount
                                                  + spending_amount
                                                  + business_amount
                                                  = starting_amount
                                              ),

                                      CONSTRAINT chk_main_simulation_event
                                          CHECK (
                                              event_type IN (
                                                             'STOCK_MARKET_DROP',
                                                             'UNEXPECTED_EXPENSE',
                                                             'DEPOSIT_INTEREST',
                                                             'BUSINESS_PROFIT'
                                                  )
                                              ),

                                      CONSTRAINT chk_main_simulation_ending
                                          CHECK (ending_amount >= 0),

                                      CONSTRAINT chk_main_simulation_xp
                                          CHECK (xp_earned >= 0)
);


CREATE INDEX idx_main_simulation_runs_child
    ON main_simulation_runs(child_profile_id);